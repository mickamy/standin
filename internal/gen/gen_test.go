package gen_test

import (
	"bytes"
	"flag"
	"os"
	"testing"

	"github.com/mickamy/standin/internal/gen"
	"github.com/mickamy/standin/internal/infer"
	"github.com/mickamy/standin/internal/parse"
)

var update = flag.Bool("update", false, "update golden files")

func TestFileGolden(t *testing.T) {
	t.Parallel()

	pkg, warnings, err := parse.Load("./testdata/model")
	if err != nil {
		t.Fatalf("parse.Load() error = %v", err)
	}

	wantWarnings := []string{"skipping generic struct Pair"}
	if len(warnings) != 1 || warnings[0] != wantWarnings[0] {
		t.Fatalf("warnings = %v, want %v", warnings, wantWarnings)
	}

	got, err := gen.File(gen.Params{
		PackageName: "fixture",
		SourceName:  pkg.Name,
		SourcePath:  pkg.Path,
		Fixtures:    infer.Fixtures(pkg.Structs, pkg.Path),
	})
	if err != nil {
		t.Fatalf("File() error = %v", err)
	}

	const golden = "testdata/fixture_gen.go.golden"

	if *update {
		if err := os.WriteFile(golden, got, 0o600); err != nil {
			t.Fatalf("update golden: %v", err)
		}
	}

	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}

	if !bytes.Equal(got, want) {
		t.Errorf("File() output differs from golden file.\ngot:\n%s\nwant:\n%s", got, want)
	}
}

func TestFile(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name   string
		params gen.Params
		want   string
	}{
		{
			name: "no fixtures",
			params: gen.Params{
				PackageName: "fixture",
				SourceName:  "model",
				SourcePath:  "example.com/app/model",
			},
			want: "// Code generated by standin. DO NOT EDIT.\n\npackage fixture\n",
		},
		{
			name: "fixture without fields skips the gofakeit import",
			params: gen.Params{
				PackageName: "fixture",
				SourceName:  "model",
				SourcePath:  "example.com/app/model",
				Fixtures:    []infer.Fixture{{Name: "Empty"}},
			},
			want: `// Code generated by standin. DO NOT EDIT.

package fixture

import (
	"example.com/app/model"
)

func Empty(setters ...func(m *model.Empty)) model.Empty {
	m := model.Empty{}
	for _, s := range setters {
		s(&m)
	}
	return m
}
`,
		},
		{
			name: "template fallback emits the mustGenerate helper",
			params: gen.Params{
				PackageName: "fixture",
				SourceName:  "model",
				SourcePath:  "example.com/app/model",
				Fixtures: []infer.Fixture{{
					Name: "User",
					Fields: []infer.FieldValue{
						{Name: "Code", Expr: `mustGenerate("###-####")`},
					},
				}},
			},
			want: `// Code generated by standin. DO NOT EDIT.

package fixture

import (
	"github.com/brianvoe/gofakeit/v7"

	"example.com/app/model"
)

func User(setters ...func(m *model.User)) model.User {
	m := model.User{
		Code: mustGenerate("###-####"),
	}
	for _, s := range setters {
		s(&m)
	}
	return m
}

func mustGenerate(template string) string {
	s, err := gofakeit.Generate(template)
	if err != nil {
		panic(err)
	}
	return s
}
`,
		},
		{
			name: "fixture with fields imports gofakeit",
			params: gen.Params{
				PackageName: "fixture",
				SourceName:  "model",
				SourcePath:  "example.com/app/model",
				Fixtures: []infer.Fixture{{
					Name: "User",
					Fields: []infer.FieldValue{
						{Name: "Name", Expr: "gofakeit.Name()"},
						{Name: "Profile", Expr: "Profile()"},
					},
				}},
			},
			want: `// Code generated by standin. DO NOT EDIT.

package fixture

import (
	"github.com/brianvoe/gofakeit/v7"

	"example.com/app/model"
)

func User(setters ...func(m *model.User)) model.User {
	m := model.User{
		Name:    gofakeit.Name(),
		Profile: Profile(),
	}
	for _, s := range setters {
		s(&m)
	}
	return m
}
`,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			got, err := gen.File(tt.params)
			if err != nil {
				t.Fatalf("File() error = %v", err)
			}

			if string(got) != tt.want {
				t.Errorf("File() = %q, want %q", got, tt.want)
			}
		})
	}
}
